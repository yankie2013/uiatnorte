// Run with jsdom available through NODE_PATH; no server or database required.
const { JSDOM } = require('jsdom');
const { readFileSync } = require('node:fs');
const assert = require('node:assert/strict');
const { join } = require('node:path');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const criteria = ['persona','vehiculo','distrito','comisaria_id'];
const dom = new JSDOM(`<header class="uiat-user-topbar"></header><div class="wrap"><main class="welcome-hero">Saludo</main><section class="welcome-workspace"><h2>¿En qué te gustaría trabajar hoy?</h2><form class="welcome-search" action="index.php" data-criterion="persona">${criteria.map((key,i)=>`<input type="radio" name="criterio" value="${key}" ${i===0?'checked':''}><div data-field="${key}" ${i?'hidden':''}><input name="valor" ${i?'disabled':''}></div>`).join('')}<button type="submit">Buscar</button><a class="welcome-clear" href="index.php">Limpiar</a><p class="welcome-status" hidden></p></form></section><nav class="welcome-shortcuts"></nav><div id="accident-filter-results" hidden></div></div><div id="welcome-pagination"></div>`, { url:'http://localhost/uiatnorte/index.php', runScripts:'outside-only', pretendToBeVisual:true });
const w=dom.window, d=w.document;
w.document.querySelector('.uiat-user-topbar').getBoundingClientRect=()=>({height:62,bottom:62});
let initialized=0;
w.initAccidentResults=()=>initialized++;
const requests=[];
w.fetch=(url,options)=>new Promise(resolve=>requests.push({url:String(url),options,resolve}));
w.HTMLElement.prototype.scrollIntoView=function() { this.dataset.scrolled='true'; };
w.eval(readFileSync(join(__dirname,'../assets/js/welcome.js'),'utf8'));
const form=d.querySelector('form');
const active=()=>form.querySelector('[name="valor"]:not(:disabled)');
const input=value=>{active().value=value;active().dispatchEvent(new w.Event('input'));};
const result=(label,page=false)=>`<div id="accident-filter-results"><div class="welcome-results-heading"><span>${label}</span></div><article class="acc-card">${label}</article></div><div id="welcome-pagination">${page?'<a href="index.php?criterio=persona&valor=ab&pagina=2">Siguiente</a>':''}</div>`;
const resolve=(index,html,ok=true)=>requests[index].resolve({ok,redirected:false,text:async()=>html});
(async()=>{
  input('a');input('ab');
  assert.equal(requests.length,0,'Search must debounce typing');
  await wait(340);
  assert.equal(requests.length,1);
  assert.equal(new URL(requests[0].url).searchParams.get('valor'),'ab');
  input('abc');await wait(340);
  assert.equal(requests[0].options.signal.aborted,true);
  resolve(1,result('new'));await wait(0);
  resolve(0,result('stale'));await wait(0);
  assert.equal(d.querySelector('.acc-card').textContent,'new','Late responses must not overwrite newer results');
  assert.equal(initialized,1,'Existing card actions must be initialized');
  input('pending');await wait(340);
  input('');
  assert.equal(d.getElementById('accident-filter-results').hidden,true);
  resolve(2,result('late after clear'));await wait(0);
  assert.equal(d.querySelector('.acc-card'),null,'Clearing must invalidate in-flight requests');
  input('escape');
  d.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  await wait(340);
  assert.equal(active().value,'');assert.equal(requests.length,3,'Escape must cancel pending debounce');
  const plate=form.querySelector('[name="criterio"][value="vehiculo"]');plate.checked=true;plate.dispatchEvent(new w.Event('change'));
  assert.equal(active().closest('[data-field]').dataset.field,'vehiculo');
  assert.equal(form.querySelectorAll('[name="valor"]:not(:disabled)').length,1);
  input('ABC');form.dispatchEvent(new w.Event('submit',{cancelable:true}));
  assert.equal(requests.length,4,'Enter/submit searches immediately');
  assert.equal(new URL(requests[3].url).searchParams.get('criterio'),'vehiculo');
  resolve(3,'',false);await wait(0);
  assert.match(form.querySelector('.welcome-status').textContent,/No pudimos/);
  assert.equal(form.hasAttribute('aria-busy'),false);
  input('pages');form.dispatchEvent(new w.Event('submit',{cancelable:true}));
  resolve(4,result('first page',true));await wait(0);
  d.querySelector('#welcome-pagination a').dispatchEvent(new w.MouseEvent('click',{bubbles:true,cancelable:true,button:0}));
  assert.equal(new URL(requests[5].url).searchParams.get('pagina'),'2');
  resolve(5,result('second page'));await wait(0);
  assert.equal(d.querySelector('.acc-card').textContent,'second page');
  assert.equal(d.getElementById('accident-filter-results').dataset.scrolled,'true');
  const sentinel=d.querySelector('.welcome-sticky-sentinel');
  sentinel.getBoundingClientRect=()=>({top:200});
  w.dispatchEvent(new w.Event('scroll'));await wait(30);
  assert.equal(d.querySelector('.welcome-workspace').classList.contains('is-stuck'),false);
  sentinel.getBoundingClientRect=()=>({top:20});
  w.dispatchEvent(new w.Event('scroll'));await wait(30);
  assert.equal(d.querySelector('.welcome-workspace').classList.contains('is-stuck'),true);
  assert.equal(d.body.style.getPropertyValue('--welcome-sticky-top'),'62px');
  assert.equal(d.querySelector('.welcome-workspace').previousElementSibling.className,'welcome-sticky-sentinel');
  form.querySelector('.welcome-clear').dispatchEvent(new w.MouseEvent('click',{bubbles:true,cancelable:true}));
  assert.equal(active().value,'');assert.equal(d.getElementById('accident-filter-results').hidden,true);
  dom.window.close();
  console.log('PASS: debounce, stale responses, clear, Escape, criteria, submit, errors, pagination and sticky activation.');
})().catch(error=>{dom.window.close();console.error(error);process.exitCode=1;});
